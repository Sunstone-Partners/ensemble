'use strict';

/**
 * TRD-007-TEST: Packaging reachability for the pr-review-cycle CLI/skill.
 *
 * Validates PRD ACs: AC-001-3, AC-019-3, AC-025-3.
 *
 * Scenario: state reports are untracked -- given a report under
 * .ensemble/pr-review/, `git check-ignore` reports the path ignored so a
 * state report can never alter the PR head.
 *
 * Scenario: mirror validation passes -- given the new pr-review-*.js lib
 * files and the new pr-review-cycle skill exist, when
 * validateFullLibMirror()/validateFullSkillsMirror() run (the same
 * functions `npm run validate` calls), then neither reports a missing
 * mirror for them.
 *
 * The remaining Test AC scenario (vendored bundle contains the CLI and its
 * modules) is covered by packages/pi/tests/lib-bundler.test.ts ("vendors
 * every real sibling module pr-review-cli.js requires").
 */

const path = require('path');
const { execFileSync } = require('child_process');
const {
  validateFullLibMirror,
  validateFullSkillsMirror,
} = require('../../../scripts/validate-all.js');

const REPO_ROOT = path.join(__dirname, '..', '..', '..');

describe('pr-review review-state report packaging', () => {
  test('.ensemble/pr-review/<file>.json is reported ignored by git check-ignore', () => {
    const target = '.ensemble/pr-review/x.json';
    let output;
    let status = 0;
    try {
      output = execFileSync('git', ['check-ignore', target], {
        cwd: REPO_ROOT,
        encoding: 'utf-8',
      });
    } catch (err) {
      status = err.status;
      output = (err.stdout || '') + (err.stderr || '');
    }

    // Exit 0 = path is ignored (the desired, safe outcome).
    expect(status).toBe(0);
    expect(output.trim()).toBe(target);
  });

  test('.gitignore declares the pr-review state directory', () => {
    const fs = require('fs');
    const gitignore = fs.readFileSync(path.join(REPO_ROOT, '.gitignore'), 'utf-8');
    expect(gitignore).toContain('.ensemble/pr-review/');
  });
});

describe('scenario: mirror validation passes', () => {
  test('packages/full/lib mirrors every pr-review-*.js file', () => {
    const failures = validateFullLibMirror();
    const prReviewFailures = failures.filter((msg) => msg.includes('pr-review-'));
    expect(prReviewFailures).toEqual([]);
  });

  test('packages/full/skills mirrors the pr-review-cycle skill', () => {
    const failures = validateFullSkillsMirror();
    const prReviewCycleFailures = failures.filter((msg) => msg.includes('pr-review-cycle'));
    expect(prReviewCycleFailures).toEqual([]);
  });
});

/**
 * TRD-034: PR 5 packaging — the metrics and eval libraries, the pr-review-eval
 * skill, the Pi skill copy, the vendored bundle and the docs.
 *
 * These assert the state `npm run validate` and `npm run generate:pi` leave
 * behind, so a PR 5 lib or skill added without re-running packaging fails
 * here rather than shipping unreachable on ensemble-full or ensemble-pi.
 */
describe('TRD-034: PR 5 packaging is refreshed', () => {
  const fs = require('fs');

  const PR5_LIBS = ['pr-review-metrics.js', 'pr-review-eval.js'];
  const PR5_SKILLS = ['pr-review-eval'];

  test.each(PR5_LIBS)('packages/full/lib/%s is a symlink resolving to the development lib', (lib) => {
    const mirror = path.join(REPO_ROOT, 'packages', 'full', 'lib', lib);
    expect(fs.lstatSync(mirror).isSymbolicLink()).toBe(true);
    expect(fs.realpathSync(mirror)).toBe(
      fs.realpathSync(path.join(REPO_ROOT, 'packages', 'development', 'lib', lib))
    );
  });

  test.each(PR5_SKILLS)('packages/full/skills/%s resolves to the development skill', (skill) => {
    const mirror = path.join(REPO_ROOT, 'packages', 'full', 'skills', skill);
    expect(fs.lstatSync(mirror).isSymbolicLink()).toBe(true);
    expect(fs.realpathSync(mirror)).toBe(
      fs.realpathSync(path.join(REPO_ROOT, 'packages', 'development', 'skills', skill))
    );
  });

  test.each(PR5_SKILLS)('packages/pi/skills/%s/SKILL.md is a generated copy', (skill) => {
    const copy = path.join(REPO_ROOT, 'packages', 'pi', 'skills', skill, 'SKILL.md');
    const content = fs.readFileSync(copy, 'utf-8');
    // The generator's own marker: how a later run recognises (and prunes) its
    // output. Its absence means the file was hand-written, not generated.
    expect(content).toContain('<!-- Generated by ensemble-pi generator');
    expect(content).toMatch(new RegExp(`^name: ${skill}$`, 'm'));
  });

  test('packages/pi/vendor/lib carries every module pr-review-cli.js requires', () => {
    const vendorLib = path.join(REPO_ROOT, 'packages', 'pi', 'vendor', 'lib');
    const cli = fs.readFileSync(
      path.join(REPO_ROOT, 'packages', 'development', 'lib', 'pr-review-cli.js'),
      'utf-8'
    );
    const required = [...cli.matchAll(/require\('\.\/([\w-]+)'\)/g)].map((m) => `${m[1]}.js`);

    // The metrics and eval libraries are the PR 5 additions; assert they are
    // actually among the CLI's requires, so this check cannot pass vacuously.
    expect(required).toEqual(expect.arrayContaining(PR5_LIBS));

    const missing = required.filter((file) => !fs.existsSync(path.join(vendorLib, file)));
    expect(missing).toEqual([]);
  });

  test('the vendored CLI reports the metrics and eval subcommands', () => {
    const vendored = path.join(REPO_ROOT, 'packages', 'pi', 'vendor', 'lib', 'pr-review-cli.js');
    let output;
    try {
      output = execFileSync('node', [vendored, 'no-such-subcommand'], {
        cwd: REPO_ROOT,
        encoding: 'utf-8',
        input: '{}',
      });
    } catch (err) {
      output = (err.stdout || '') + (err.stderr || '');
    }
    for (const sub of ['metrics', 'metrics-compare', 'eval-score', 'eval-compare', 'eval-stale']) {
      expect(output).toContain(sub);
    }
  });

  test('README and CHANGELOG describe metrics, eval and the baseline-capture entry criterion', () => {
    const readme = fs.readFileSync(path.join(REPO_ROOT, 'README.md'), 'utf-8');
    const changelog = fs.readFileSync(path.join(REPO_ROOT, 'CHANGELOG.md'), 'utf-8');

    for (const doc of [readme, changelog]) {
      expect(doc).toContain('metrics-compare');
      expect(doc).toContain('eval-score');
      expect(doc).toContain('pr-review-eval');
      // The entry criterion: a baseline captured before the change lands.
      expect(doc).toContain('docs/guides/review-baseline-');
      expect(doc).toContain('docs/guides/pr-review-metrics.md');
    }
  });
});
