'use strict';

/**
 * TRD-022: PR 3 packaging, mirrors, generation and version files.
 *
 * PR 3 ships the verification surface -- the depth/slice and vote modules, the
 * reviewer dispatch and verification steps of the `pr-review-cycle` skill, and
 * the read-only `code-reviewer` agent. None of that is reachable for an
 * installed user unless packaging keeps up with it, and packaging failures are
 * invisible in the source tree: the library is right there in
 * `packages/development/lib/`, it is just missing from the full-plugin mirror
 * or from the Pi vendor bundle, so the feature works in this repository and
 * nowhere else.
 *
 * These assert the state `npm run validate` and `npm run generate:pi` leave
 * behind, from the repository on disk:
 *
 *   - every PR 3 library is mirrored into `packages/full/lib/`;
 *   - the `pr-review-cycle` skill is mirrored into `packages/full/skills/` and
 *     copied, generated, into `packages/pi/skills/`, carrying the PR 3 prose;
 *   - the Pi vendor bundle carries the CLI and EVERY sibling it requires, so a
 *     vendored `pr-review-cli.js` cannot throw MODULE_NOT_FOUND on the first
 *     real call, and the vendored CLI is the one in this tree;
 *   - the generated `code-reviewer` artifacts (Claude md, Pi md, Codex toml)
 *     carry the read-only contract TRD-020 put in the YAML;
 *   - the version files of the two packages PR 3 changes (development and
 *     quality) agree across package.json, plugin.json and both marketplace
 *     manifests -- an install gates on that string, so a package whose
 *     manifests disagree serves stale content forever.
 */

const fs = require('fs');
const { readSkillBundle } = require('./helpers/pr-review-cycle-skill');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');
const DEV_LIB = path.join(REPO_ROOT, 'packages', 'development', 'lib');
const FULL_LIB = path.join(REPO_ROOT, 'packages', 'full', 'lib');
const PI_VENDOR_LIB = path.join(REPO_ROOT, 'packages', 'pi', 'vendor', 'lib');

/** The libraries PR 3 adds or changes: verification, depth/slices and the ledger they feed. */
const PR3_LIBS = ['pr-review-votes.js', 'pr-review-depth.js', 'pr-review-ledger.js', 'pr-review-cli.js'];

const read = (...parts) => fs.readFileSync(path.join(...parts), 'utf8');

describe('TRD-022: PR 3 libraries are mirrored into the full plugin', () => {
  test.each(PR3_LIBS)('packages/full/lib/%s resolves to the development library', (lib) => {
    const mirror = path.join(FULL_LIB, lib);
    expect(fs.existsSync(mirror)).toBe(true);
    expect(fs.realpathSync(mirror)).toBe(fs.realpathSync(path.join(DEV_LIB, lib)));
  });

  test('the mirror is complete: every pr-review library in development is in packages/full/lib', () => {
    const sourced = fs.readdirSync(DEV_LIB).filter((name) => /^pr-review-.*\.js$/.test(name));
    expect(sourced).toEqual(expect.arrayContaining(PR3_LIBS));

    const missing = sourced.filter((name) => !fs.existsSync(path.join(FULL_LIB, name)));
    expect(missing).toEqual([]);
  });
});

describe('TRD-022: the pr-review-cycle skill is mirrored and copied with its PR 3 prose', () => {
  const SOURCE = path.join(REPO_ROOT, 'packages', 'development', 'skills', 'pr-review-cycle', 'SKILL.md');

  test('packages/full/skills/pr-review-cycle resolves to the development skill', () => {
    const mirror = path.join(REPO_ROOT, 'packages', 'full', 'skills', 'pr-review-cycle');
    expect(fs.existsSync(mirror)).toBe(true);
    expect(fs.realpathSync(mirror)).toBe(fs.realpathSync(path.dirname(SOURCE)));
  });

  test('the Pi copy is generated (not hand-written) and carries the PR 3 verification steps', () => {
    const piDir = path.join(REPO_ROOT, 'packages', 'pi', 'skills', 'pr-review-cycle');
    const copy = read(REPO_ROOT, 'packages', 'pi', 'skills', 'pr-review-cycle', 'SKILL.md');
    expect(copy).toContain('<!-- Generated by ensemble-pi generator');
    // The skill is SKILL.md plus the companions it names; the Pi copier ships those too.
    const copyBundle = readSkillBundle(piDir);

    // The parts of the skill PR 3 added: without these the Pi copy is stale and
    // a Pi user gets the pre-verification loop while this repo gets the new one.
    const flat = copyBundle.replace(/\s+/g, ' ');
    const source = readSkillBundle().replace(/\s+/g, ' ');
    for (const promise of [
      'Step 3b -- Verify the candidates before they are presented',
      'Ingesting CodeRabbit and other review-bot findings',
      'REDUCED REVIEW:',
      'Each reviewer starts in **fresh context**',
    ]) {
      expect([promise, source.includes(promise)]).toEqual([promise, true]);
      expect([promise, flat.includes(promise)]).toEqual([promise, true]);
    }
  });
});

describe('TRD-022: the Pi vendor bundle carries the CLI and its whole require closure', () => {
  const cliSource = read(DEV_LIB, 'pr-review-cli.js');
  const requiredSiblings = [...new Set([...cliSource.matchAll(/require\('\.\/([\w-]+)'\)/g)].map((m) => `${m[1]}.js`))];

  test('the CLI really requires the PR 3 verification modules (so this check cannot pass vacuously)', () => {
    expect(requiredSiblings).toEqual(expect.arrayContaining(['pr-review-votes.js', 'pr-review-depth.js']));
  });

  test.each(['pr-review-cli.js', ...PR3_LIBS])('packages/pi/vendor/lib/%s is vendored', (lib) => {
    expect(fs.existsSync(path.join(PI_VENDOR_LIB, lib))).toBe(true);
  });

  test('every sibling the CLI requires is vendored beside it', () => {
    const missing = requiredSiblings.filter((name) => !fs.existsSync(path.join(PI_VENDOR_LIB, name)));
    expect(missing).toEqual([]);
  });

  test('the vendored CLI is the CLI in this tree, not an older copy of it', () => {
    const vendored = read(PI_VENDOR_LIB, 'pr-review-cli.js');
    // Vendoring may add a header, so compare the shipped surface, not bytes.
    for (const subcommand of ['votes:', 'depth:', 'slices:', 'ledger:']) {
      expect([subcommand, vendored.includes(subcommand)]).toEqual([subcommand, true]);
    }
    expect(vendored).toContain('const HANDLERS = Object.freeze({');
  });
});

describe('TRD-022: the generated code-reviewer artifacts carry the read-only contract', () => {
  const MARKDOWN = [
    ['packages', 'quality', 'agents', 'code-reviewer.md'],
    ['packages', 'pi', 'agents', 'code-reviewer.md'],
  ];
  const TOML = ['packages', 'codex', '.codex', 'agents', 'code-reviewer.toml'];
  const ALL = [...MARKDOWN, TOML];

  const label = (parts) => path.join(...parts.slice(1));

  test.each(MARKDOWN.map((parts) => [label(parts)]))('%s grants no write tool in its frontmatter', (relative) => {
    const parts = MARKDOWN.find((entry) => label(entry) === relative);
    const toolLines = read(REPO_ROOT, ...parts)
      .split('\n')
      .filter((line) => /^tools:/.test(line));

    // The frontmatter really declares tools, so this cannot pass by matching nothing.
    expect(toolLines).toHaveLength(1);
    expect(toolLines[0]).toContain('Read');
    expect(/\b(Write|Edit|MultiEdit|NotebookEdit)\b/.test(toolLines[0])).toBe(false);
  });

  test.each(ALL.map((parts) => [label(parts)]))('%s states the read-only contract TRD-020 put in the YAML', (relative) => {
    const parts = ALL.find((entry) => label(entry) === relative);
    const text = read(REPO_ROOT, ...parts);
    const flat = text.replace(/\s+/g, ' ');

    expect(flat).toContain('READ-ONLY code review agent');
    expect(flat).toContain('You may record or post findings only. You never edit, write, fix, stage, commit or revert');
    // The structured finding contract the ledger and the verifiers consume.
    expect(flat).toContain('Output Contract');
    expect(flat).toContain('`severity`');
  });

  test('the YAML the artifacts are generated from is the single source, and says so in them', () => {
    const yaml = read(REPO_ROOT, 'packages', 'quality', 'agents', 'code-reviewer.yaml');
    expect(yaml).toContain('code-reviewer');
    expect(yaml).toContain('READ-ONLY code review agent');

    for (const parts of ALL) {
      const text = read(REPO_ROOT, ...parts);
      // Each generator writes its own marker; what matters is that all three
      // name the YAML as the source, so none of them is hand-edited.
      const generated = /Generated (from|by)[^\n]*code-reviewer\.yaml/.test(text);
      expect([label(parts), generated]).toEqual([label(parts), true]);
    }
  });
});

describe('TRD-022: the version files of the packages PR 3 changes are in sync', () => {
  const PACKAGES = [
    ['development', 'ensemble-development'],
    ['quality', 'ensemble-quality'],
  ];

  test.each(PACKAGES)('packages/%s declares one version across all four manifests', (dir, pluginName) => {
    const pkg = JSON.parse(read(REPO_ROOT, 'packages', dir, 'package.json'));
    const plugin = JSON.parse(read(REPO_ROOT, 'packages', dir, '.claude-plugin', 'plugin.json'));
    const rootMarket = JSON.parse(read(REPO_ROOT, 'marketplace.json'));
    const pluginMarket = JSON.parse(read(REPO_ROOT, '.claude-plugin', 'marketplace.json'));

    const entryOf = (manifest) => manifest.plugins.find((entry) => entry.name === pluginName);
    expect(entryOf(rootMarket)).toBeDefined();
    expect(entryOf(pluginMarket)).toBeDefined();

    expect([plugin.version, entryOf(rootMarket).version, entryOf(pluginMarket).version]).toEqual([
      pkg.version,
      pkg.version,
      pkg.version,
    ]);
  });

  test('both marketplace manifests stay byte-identical, as validate-all requires', () => {
    expect(read(REPO_ROOT, 'marketplace.json')).toBe(read(REPO_ROOT, '.claude-plugin', 'marketplace.json'));
  });
});
