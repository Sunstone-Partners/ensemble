/**
 * The generator's proof of authorship.
 *
 * Pruning removes a file only when it can prove the generator wrote it (see generator.ts), so
 * the proof has to be written by every writer and recognised by exactly what the writers
 * produce. This file pins the marker helpers, that each transformer stamps its output, and the
 * command-wrapper recognizer. The generator-level behaviour built on them is in
 * prune-stale.test.ts.
 */

import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import matter from 'gray-matter';
import {
  COMMAND_HEADER_PREFIX,
  GENERATED_MARKER_PREFIX,
  commandHeaderLine,
  generatedMarker,
  hasGeneratedMarker,
  withGeneratedMarker,
} from '../src/generated-marker';
import { transformAgent } from '../src/transformers/agent-transformer';
import { transformCommand } from '../src/transformers/command-transformer';
import {
  generateCommandSkills,
  isCommandWrapperSkill,
} from '../src/transformers/command-skill-transformer';
import { CommandYaml } from '../src/types';

const MARKER = generatedMarker('some/source.md');

describe('generated marker helpers', () => {
  it('is, byte for byte, the header line command prompts have always carried', () => {
    expect(generatedMarker('prd.yaml')).toBe(
      '<!-- Generated by ensemble-pi generator v1.0.0 | Source: prd.yaml -->'
    );
    expect(generatedMarker('prd.yaml').startsWith(GENERATED_MARKER_PREFIX)).toBe(true);
  });

  it('builds the Command header line from the same prefix wrappers are recognised by', () => {
    expect(commandHeaderLine('ensemble-prd', '1.1.0')).toBe('<!-- Command: ensemble-prd | Version: 1.1.0 -->');
    expect(commandHeaderLine('ensemble-prd', '1.1.0').startsWith(COMMAND_HEADER_PREFIX)).toBe(true);
  });

  describe('withGeneratedMarker', () => {
    it('puts the marker on the first line of a file without frontmatter and changes nothing else', () => {
      expect(withGeneratedMarker('# Title\n\nBody\n', 'some/source.md')).toBe(`${MARKER}\n# Title\n\nBody\n`);
    });

    it('puts the marker on the first line after the frontmatter and leaves both parts alone', () => {
      expect(withGeneratedMarker('---\nname: x\n---\n\n# Title\n', 'some/source.md')).toBe(
        `---\nname: x\n---\n${MARKER}\n\n# Title\n`
      );
    });

    it('handles a file that is only frontmatter, and an empty one', () => {
      expect(withGeneratedMarker('---\nname: x\n---\n', 'some/source.md')).toBe(`---\nname: x\n---\n${MARKER}\n`);
      expect(withGeneratedMarker('', 'some/source.md')).toBe(`${MARKER}\n`);
    });

    it('treats an empty frontmatter block as frontmatter', () => {
      expect(withGeneratedMarker('---\n---\nBody\n', 'some/source.md')).toBe(`---\n---\n${MARKER}\nBody\n`);
    });
  });

  describe('hasGeneratedMarker', () => {
    it.each([
      ['no frontmatter', '# Title\n\nBody\n'],
      ['frontmatter', '---\nname: x\ndescription: y\n---\n\n# Title\n'],
      ['empty frontmatter', '---\n---\nBody\n'],
      ['frontmatter only', '---\nname: x\n---\n'],
      ['CRLF frontmatter', '---\r\nname: x\r\n---\r\n# Title\r\n'],
      ['empty', ''],
      ['a horizontal rule that opens like frontmatter', '---\nnot yaml at all\n---\nBody\n'],
    ])('accepts what withGeneratedMarker wrote: %s', (_label, content) => {
      expect(hasGeneratedMarker(withGeneratedMarker(content, 'some/source.md'))).toBe(true);
    });

    it('allows blank lines between the frontmatter and the marker, as agent files have', () => {
      expect(hasGeneratedMarker(`---\nname: x\n---\n\n\n${MARKER}\n\n# x\n`)).toBe(true);
    });

    it.each([
      ['an empty file', ''],
      ['a plain document', '# Title\n\nBody\n'],
      ['a marker after a heading', `# Title\n\n${MARKER}\n`],
      ['a marker after body text', `Some text first\n${MARKER}\n`],
      ['a marker quoted in a fenced block', `\`\`\`\n${MARKER}\n\`\`\`\n`],
      ['a marker inside the frontmatter', `---\nnote: "${MARKER}"\n---\n# Title\n`],
      ['a marker on the frontmatter line itself', `---\n${MARKER}\n# Title\n`],
      ['another generator\'s header', '<!-- DO NOT EDIT - Generated from x.yaml -->\n# Title\n'],
      ['the prefix with a different generator name', '<!-- Generated by something else -->\n'],
      ['frontmatter and no marker', '---\nname: x\n---\n\n# Title\n'],
    ])('rejects %s', (_label, content) => {
      expect(hasGeneratedMarker(content)).toBe(false);
    });
  });
});

describe('every writer stamps what it writes', () => {
  const COMMAND: CommandYaml = {
    metadata: { name: 'ensemble:x', description: 'The x command', version: '1.0.0' },
    workflow: {
      phases: [{ id: 1, name: 'Do it', steps: [{ id: 1, title: 'Step', description: 'Do the thing' }] }],
    },
    mission: { summary: 'Summary of x' },
  };

  it('command prompts open with the marker and then the Command line', () => {
    const [first, second] = transformCommand(COMMAND, '/repo/packages/p/commands/x.yaml', {}).split('\n');
    expect(first).toBe(generatedMarker('x.yaml'));
    expect(second).toBe(commandHeaderLine('ensemble-x', '1.0.0'));
  });

  it('agents carry the marker right after the frontmatter, which still parses', () => {
    const output = transformAgent(
      { name: 'helper', description: 'Helps', tools: ['Read'] },
      '/repo/packages/p/agents/helper.yaml',
      {}
    );
    expect(output.startsWith('---\n')).toBe(true);
    const parsed = matter(output);
    expect(parsed.data.name).toBe('helper');
    expect(parsed.content.trim().startsWith(generatedMarker('helper.yaml'))).toBe(true);
    expect(parsed.content).toContain('# helper');
    expect(hasGeneratedMarker(output)).toBe(true);
  });
});

describe('isCommandWrapperSkill', () => {
  const NAME = 'ensemble-x';
  let root: string;
  let wrapper: string;

  beforeAll(async () => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), 'pi-wrapper-'));
    const command: CommandYaml = {
      metadata: { name: 'ensemble:x', description: 'The x command', version: '1.0.0' },
      workflow: {
        phases: [{ id: 1, name: 'Do it', steps: [{ id: 1, title: 'Step', description: 'Do the thing' }] }],
      },
      mission: { summary: 'Summary of x' },
    };
    fs.mkdirSync(path.join(root, 'prompts'), { recursive: true });
    fs.writeFileSync(path.join(root, 'prompts', `${NAME}.md`), transformCommand(command, 'x.yaml', {}), 'utf-8');
    await generateCommandSkills(root, {});
    wrapper = fs.readFileSync(path.join(root, 'skills', NAME, 'SKILL.md'), 'utf-8');
  });

  afterAll(() => {
    fs.rmSync(root, { recursive: true, force: true });
  });

  it('accepts the wrapper generateCommandSkills writes, with or without the Claude Code flag', async () => {
    expect(isCommandWrapperSkill(NAME, wrapper)).toBe(true);

    await generateCommandSkills(root, { hideFromClaudeCode: true });
    const hidden = fs.readFileSync(path.join(root, 'skills', NAME, 'SKILL.md'), 'utf-8');
    expect(hidden).toContain('user-invocable: false');
    expect(isCommandWrapperSkill(NAME, hidden)).toBe(true);
  });

  it('keeps the prompt\'s Command line as the first line of the body: that is what ties it to its command', () => {
    expect(matter(wrapper).content.trimStart().startsWith(commandHeaderLine(NAME, '1.0.0'))).toBe(true);
  });

  it.each([
    ['a directory of another name', (c: string) => ({ dir: 'ensemble-y', content: c })],
    ['a directory without the ensemble- prefix, and a name to match it', (c: string) => ({ dir: 'x', content: c.replace('name: ensemble-x', 'name: x') })],
    [
      'a directory without the ensemble- prefix that is otherwise a perfect wrapper',
      (c: string) => ({ dir: 'x', content: c.replaceAll('ensemble-x', 'x') }),
    ],
    [
      'the flag set to false',
      (c: string) => ({ dir: NAME, content: c.replace('disable-model-invocation: true', 'disable-model-invocation: false') }),
    ],
    [
      'no flag',
      (c: string) => ({ dir: NAME, content: c.replace('disable-model-invocation: true\n', '') }),
    ],
    ['a frontmatter name that is not the directory', (c: string) => ({ dir: NAME, content: c.replace('name: ensemble-x', 'name: ensemble-z') })],
    ['no Command line', (c: string) => ({ dir: NAME, content: c.replace(/^<!-- Command: .*-->\n/m, '') })],
    [
      'the Command line of another command',
      (c: string) => ({ dir: NAME, content: c.replace('<!-- Command: ensemble-x |', '<!-- Command: ensemble-xy |') }),
    ],
    ['frontmatter that does not parse', (c: string) => ({ dir: NAME, content: c.replace('name: ensemble-x', 'name: [unclosed') })],
    ['no frontmatter at all', (c: string) => ({ dir: NAME, content: matter(c).content })],
  ])('rejects %s', (_label, mutate) => {
    const { dir, content } = mutate(wrapper);
    // The mutation really changed something: the directory or the content
    expect(dir !== NAME || content !== wrapper).toBe(true);
    expect(isCommandWrapperSkill(dir, content)).toBe(false);
  });
});
