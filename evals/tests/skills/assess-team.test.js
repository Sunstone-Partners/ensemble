'use strict';

/**
 * Kit test for the `assess-team` eval: a good report and six dimension files pass every check, and plausible wrong outputs each fail
 * the check named (see evals/skills/assess-team/README.md). No model is called.
 */

const kit = require('../skill-eval-kit');

jest.setTimeout(60000);

const ID = 'assess-team';
const REPORT = 'docs/assessment/team-2026-03-02.md';
const DIMS = ['commit-messages', 'code-quality', 'test-coverage', 'ai-adoption', 'documentation', 'code-review'];
const file = (d) => `docs/assessment/team-fixture-${d}.md`;

const BODY = {
  'commit-messages': 'The repository history is a single commit, so no message convention, trend or quality distribution can be measured.\nNo evidence found in local git for message quality over time [confidence: LOW].',
  'code-quality': '6 debt markers: 4 TODO and 2 FIXME comments across the services and lib/util.js.\nservices/payments/index.js:5 FIXME refunds are not recorded.\nNo large files.',
  'test-coverage': 'Two test files cover orders and util.\nservices/payments has no tests although it moves money: the main gap.\ninventory and notify are also untested.',
  'ai-adoption': '3 of 5 source files carry a Generated by or AI-Generated marker (lib/util.js, services/orders, services/notify).\nNo CI AI checks. No AI attribution policy.\nCopilot usage statistics: No evidence found in local git [confidence: MEDIUM - requires API to verify].',
  documentation: 'Only 1 of 4 services has a README.\npayments, inventory and notify have no README.\ndocs/ARCHITECTURE.md is short but current.',
  'code-review': 'Cannot verify peer review from local git [confidence: LOW - requires API]. Run `gh pr list --state merged --limit 100` to get it.\nNo merge commits exist in this history.',
};
const SCORE = { 'commit-messages': '2.0 / D', 'code-quality': '3.5 / B-', 'test-coverage': '2.3 / D+', 'ai-adoption': '3.0 / C', documentation: '2.2 / D+', 'code-review': '2.0 / D' };
const dimension = (d, score = SCORE[d]) => `# Team Assessment: ${d}\n\n## Findings\n\n${BODY[d]}\n\n## Key Findings\n\n1. See above [confidence: MEDIUM]\n\n## Score: ${score} (rationale)\n\n## Recommendations\n\n1. Act.\n`;

const rowsOf = (over = {}) => {
  const s = { Overall: '2.6 / C-', 'Commit Messages': '2.0 / D', 'Code Quality': '3.5 / B-', 'Test Coverage': '2.3 / D+', 'AI Adoption': '3.0 / C', Documentation: '2.2 / D+', 'Code Review': '2.0 / D', ...over };
  return Object.entries(s).map(([k, v]) => { const [n, l] = v.split(' / '); return `| ${k} | ${n} | ${l} | finding |`; }).join('\n');
};

const report = ({ rows = rowsOf(), limits, extra = '' } = {}) => `# Team Assessment Report

**Date:** 2026-03-02

---

## Executive Summary

A small team with thin tests and one commit of history.

---

## Overall Scores

| Assessment | Score | Grade | Key Finding |
|------------|------:|-------|-------------|
${rows}

---

## 1. Commit Messages

### Key Findings
1. Single commit.

## 2. Code Quality

### Key Findings
1. Six debt markers.

## 3. Test Coverage

### Key Findings
1. Payments untested.

## 4. AI Adoption

### Key Findings
1. Three marked files.

## 5. Documentation

### Key Findings
1. Three services lack a README.

## 6. Code Review

### Key Findings
1. Cannot verify peer review from local git.
${extra}
---

## Recommendations — Priority Order

### Priority 1: Tests
Cover payments.

---

## Data Limitations

${limits || `- PR review and approval data (requires GitHub API)
- Copilot usage statistics: No evidence found in local git
- Incident response (not assessed: no data source in local git)`}

---

## Agent Output Files

${DIMS.map((d) => `- [${d}](docs/assessment/team-fixture-${d}.md)`).join('\n')}
`;

/** A stub agent that saves the report and the six dimension files; `over` replaces any of them (null skips it). */
const saves = ({ rep = report(), dims = {}, more = {} } = {}) => (ws) => {
  if (rep !== null) ws.write(REPORT, rep);
  for (const d of DIMS) {
    const text = d in dims ? dims[d] : dimension(d);
    if (text !== null) ws.write(file(d), text);
  }
  for (const [rel, body] of Object.entries(more)) ws.write(rel, body);
};

describe(`${ID} (kit)`, () => {
  test('loads clean: valid definition, fixture without agent or git configuration', () => {
    expect(kit.loadsClean(ID).fixtureDir).toBeTruthy();
  });

  test('a good report with six dimension files passes every check', async () => {
    const res = await kit.runEval(ID, saves());
    expect(Object.keys(res)).toEqual(['report-saved', 'report-sections', 'dimension-files', 'overall-scores', 'code-review-cap', 'data-limitations',
      'privacy-no-individuals', 'history-honest', 'test-gap-found', 'docs-gap-found', 'ai-markers', 'debt-count', 'no-stray-writes']);
    kit.expectAllPass(res);
  });

  test('a run that writes nothing fails every content check and passes the no-write check', async () => {
    const res = await kit.runEval(ID, saves({ rep: null, dims: Object.fromEntries(DIMS.map((d) => [d, null])) }));
    const failing = Object.entries(res).filter(([, r]) => !r.pass).map(([k]) => k);
    expect(failing).toEqual(Object.keys(res).filter((k) => k !== 'no-stray-writes'));
  });

  test('missing dimension files fail dimension-files and the report links', async () => {
    const res = await kit.runEval(ID, saves({ dims: { 'ai-adoption': null, 'code-review': null } }));
    kit.expectFails(res, 'dimension-files', /ai-adoption: no file/);
    expect(res['report-sections'].pass).toBe(false);
  });

  test('a dimension score whose letter is off the shared scale fails dimension-files', async () => {
    const res = await kit.runEval(ID, saves({ dims: { 'code-quality': dimension('code-quality', '3.5 / A') } }));
    kit.expectFails(res, 'dimension-files', /3\.5 is B-/, { only: true });
  });

  test('a report without the title fails report-saved; a dimension score outside 1.0-5.0 fails dimension-files; too few category sections fail report-sections', async () => {
    kit.expectFails(await kit.runEval(ID, saves({ rep: report().replace('# Team Assessment Report', '# Summary') })), 'report-saved', /title/, { only: true });
    kit.expectFails(await kit.runEval(ID, saves({ dims: { 'code-quality': dimension('code-quality', '0.5 / F') } })), 'dimension-files', /outside 1\.0-5\.0/, { only: true });
    const few = report().replace(/## [3-6]\. /g, '### ');
    kit.expectFails(await kit.runEval(ID, saves({ rep: few })), 'report-sections', /only 2 numbered category/, { only: true });
  });

  test('an incident row and a wrong letter fail overall-scores', async () => {
    kit.expectFails(await kit.runEval(ID, saves({ rep: report({ rows: `${rowsOf()}\n| Incident Response | 3.0 | C | made up |` }) })), 'overall-scores', /unexpected row/, { only: true });
    kit.expectFails(await kit.runEval(ID, saves({ rep: report({ rows: rowsOf({ Documentation: '2.2 / B' }) }) })), 'overall-scores', /Documentation: 2\.2 is D\+/, { only: true });
  });

  test('a Code Review score above the 2.0 cap fails code-review-cap', async () => {
    const rep = report({ rows: rowsOf({ 'Code Review': '3.5 / B-' }) });
    kit.expectFails(await kit.runEval(ID, saves({ rep })), 'code-review-cap', /cap is 2\.0/, { only: true });
  });

  test('a report that gives a Code Review score without the data limitation fails code-review-cap', async () => {
    const quiet = { 'code-review': dimension('code-review').replace(BODY['code-review'], 'Merges look healthy.') };
    const rep = report().replace('Cannot verify peer review from local git.', 'Reviews are fine.');
    kit.expectFails(await kit.runEval(ID, saves({ rep, dims: quiet })), 'code-review-cap', /cannot be verified/, { only: true });
  });

  test('Data Limitations that omit the incident note, and an N/A cell, fail data-limitations', async () => {
    const limits = '- PR review data (requires GitHub API)\n- No evidence found in local git for Copilot';
    kit.expectFails(await kit.runEval(ID, saves({ rep: report({ limits }) })), 'data-limitations', /incident/, { only: true });
    kit.expectFails(await kit.runEval(ID, saves({ rep: report({ extra: '\n| Thing | N/A |\n' }) })), 'data-limitations', /N\/A/, { only: true });
  });

  test('naming a contributor, or a per-author table, fails privacy-no-individuals', async () => {
    const named = { documentation: `${dimension('documentation')}\nMost docs were written by Pat Placeholder.\n` };
    kit.expectFails(await kit.runEval(ID, saves({ dims: named })), 'privacy-no-individuals', /names Pat Placeholder/, { only: true });
    const table = { 'commit-messages': `${dimension('commit-messages')}\n| Author | Commits |\n|---|---|\n| someone | 9 |\n` };
    kit.expectFails(await kit.runEval(ID, saves({ dims: table })), 'privacy-no-individuals', /per-author table/, { only: true });
  });

  test('a commit-messages analysis that ignores the one-commit history fails history-honest', async () => {
    const d = { 'commit-messages': dimension('commit-messages').replace(BODY['commit-messages'], '78% of 100 sampled commits follow the conventional format; the trend is improving.') };
    kit.expectFails(await kit.runEval(ID, saves({ dims: d })), 'history-honest', /single commit/, { only: true });
  });

  test('missing the untested payments service fails test-gap-found; the wrong service named does not pass', async () => {
    const d = { 'test-coverage': dimension('test-coverage').replace(BODY['test-coverage'], 'Orders and util are tested.\ninventory has no tests.') };
    kit.expectFails(await kit.runEval(ID, saves({ dims: d })), 'test-gap-found', /payments/, { only: true });
  });

  test('naming fewer than two undocumented services fails docs-gap-found', async () => {
    const d = { documentation: dimension('documentation').replace(BODY.documentation, 'payments has no README.\nThe docs folder is current.') };
    kit.expectFails(await kit.runEval(ID, saves({ dims: d })), 'docs-gap-found', /names 1 of the 3/, { only: true });
  });

  test('a wrong AI-marker count fails ai-markers', async () => {
    const d = { 'ai-adoption': dimension('ai-adoption').replace('3 of 5', '5 of 5') };
    kit.expectFails(await kit.runEval(ID, saves({ dims: d })), 'ai-markers', /3 files/, { only: true });
  });

  test('a wrong TODO/FIXME count fails debt-count', async () => {
    const d = { 'code-quality': dimension('code-quality').replace('6 debt markers: 4 TODO and 2 FIXME', '9 debt markers: 7 TODO and 2 FIXME') };
    kit.expectFails(await kit.runEval(ID, saves({ dims: d })), 'debt-count', /count of 6/, { only: true });
  });

  test('a report with sections out of order fails report-sections', async () => {
    const rep = `${report().replace('## Executive Summary', '## Summary')}\n## Executive Summary\n\nlate\n`;
    kit.expectFails(await kit.runEval(ID, saves({ rep })), 'report-sections', /Overall Scores.*\(order\)/, { only: true });
  });

  test('a file written outside docs/assessment, or a changed fixture file, fails no-stray-writes', async () => {
    kit.expectFails(await kit.runEval(ID, saves({ more: { 'NOTES.md': 'x\n' } })), 'no-stray-writes', /NOTES\.md/, { only: true });
    kit.expectFails(await kit.runEval(ID, saves({ more: { 'lib/util.js': '// changed\n' } })), 'no-stray-writes', /modified/, { only: true });
  });

  test('arms: baseline loads nothing, with-skill loads packages/assessment; the prompt is plain in both', async () => {
    const { baseline, withSkill } = await kit.armsFor(ID);
    expect(baseline.plugins).toEqual([]);
    expect(withSkill.plugins).toHaveLength(1);
    expect(withSkill.plugins[0]).toMatch(/packages\/assessment$/);
    expect(withSkill.prompt).toBe(baseline.prompt);
    expect(baseline.prompt).not.toMatch(/^\//);
  });
});
