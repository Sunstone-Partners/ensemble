'use strict';

/** Proof that the checks of the `ensemble-discover-standards` eval pass on good output and fail on bad output (evals/tests/skill-eval-kit.js). */

const kit = require('../skill-eval-kit');
const { parseIndex } = require('../../checks/ensemble-discover-standards');

const ID = 'ensemble-discover-standards';

const INDEX = `version: 1
generated: 2026-11-13
stack:
  language: JavaScript (Node.js)
  framework: none
  test_framework: node:test
  linter: eslint
standards:
  naming:
    - id: naming-001
      rule: Source files use kebab-case names
      example: line-item.js
    - id: naming-002
      rule: Functions and variables use camelCase
      example: orderTotal
    - id: naming-003
      rule: Classes use PascalCase
      example: LineItem
    - id: naming-004
      rule: Error classes end in Error
      example: ValidationError
  testing:
    - id: testing-001
      rule: Prefer table-driven tests: loop over cases calling test() once per case
    - id: testing-002
      rule: Test files live in test/ and are named *-test.js
      example: test/order-test.js
  imports:
    - id: imports-001
      rule: Modules are re-exported through the src/index.js barrel
  error_handling:
    - id: error_handling-001
      rule: Throw ValidationError (extends Error) with the offending field
      example: new ValidationError('sku is required', 'sku')
  git:
    - id: git-001
      rule: Run npm test before committing
`;
const NAMING_MD = '# Naming\n\nFiles are kebab-case, functions camelCase, classes PascalCase, error classes end in Error.\n';
const CLAUDE = '# order-utils\n\nSmall library that totals customer orders. Run `npm test` before committing.\n\n## Standards\nSee `standards/index.yml` for coding conventions (auto-generated by /ensemble:standards discover).\n';

/** A stub agent that writes the standards; each argument overrides one piece (null skips it). */
const agent = ({ index = INDEX, naming = NAMING_MD, claude = CLAUDE, extra = {} } = {}) => (ws) => {
  if (index !== null) ws.write('standards/index.yml', index);
  if (naming !== null) ws.write('standards/naming.md', naming);
  if (claude !== null) ws.write('CLAUDE.md', claude);
  for (const [rel, body] of Object.entries(extra)) ws.write(rel, body);
};

describe(`${ID}`, () => {
  test('loads clean: valid definition, fixture without agent or git configuration', () => {
    expect(kit.loadsClean(ID).fixtureDir).toBeTruthy();
  });

  test('good output passes every check', async () => {
    const res = await kit.runEval(ID, agent());
    expect(Object.keys(res)).toEqual(['index-saved', 'index-stack', 'rules-wellformed', 'merge-preserved', 'rules-grounded', 'category-docs', 'claude-pointer', 'scope-only']);
    kit.expectAllPass(res);
  });

  test('quoted values and a quoted-key style index also pass', async () => {
    const quoted = INDEX.replace(/^(\s+(?:rule|id|example): )(.*)$/gm, (_, k, v) => `${k}"${v}"`);
    kit.expectAllPass(await kit.runEval(ID, agent({ index: quoted })));
  });

  test('the parser reads the seeded shape', () => {
    const idx = parseIndex(INDEX);
    expect(idx.stack.test_framework).toBe('node:test');
    expect(idx.categories.naming).toHaveLength(4);
    expect(idx.categories.naming[0]).toMatchObject({ id: 'naming-001', rule: 'Source files use kebab-case names' });
  });

  test('a run that does nothing fails the checks about new output', async () => {
    const res = await kit.runEval(ID, () => {});
    kit.expectFails(res, ['rules-wellformed', 'rules-grounded', 'claude-pointer'], undefined, { only: true });
    expect(res['rules-wellformed'].detail).toMatch(/only 2 rules/);
  });

  test('no index written fails the index checks', async () => {
    // the seeded index is deleted, as if the run replaced it with nothing
    const res = await kit.runEval(ID, (ws) => { ws.remove('standards/index.yml'); ws.write('CLAUDE.md', CLAUDE); });
    kit.expectFails(res, ['index-saved', 'index-stack', 'rules-wellformed', 'merge-preserved', 'rules-grounded', 'category-docs'], /was not written/, { only: true });
  });

  test('a stack that does not match the fixture fails index-stack', async () => {
    const res = await kit.runEval(ID, agent({ index: INDEX.replace('test_framework: node:test', 'test_framework: pytest') }));
    kit.expectFails(res, 'index-stack', /fixture uses node:test/, { only: true });
  });

  test('a missing stack key fails index-stack', async () => {
    const res = await kit.runEval(ID, agent({ index: INDEX.replace('  linter: eslint\n', '') }));
    kit.expectFails(res, 'index-stack', /stack\.linter is missing/, { only: true });
  });

  test('a rule over 79 characters fails rules-wellformed', async () => {
    const long = INDEX.replace('Classes use PascalCase', 'Classes use PascalCase and every class lives in its own file named after the class in kebab-case');
    kit.expectFails(await kit.runEval(ID, agent({ index: long })), 'rules-wellformed', /naming-003 rule is \d+ characters/, { only: true });
  });

  test('an id with the wrong category prefix or a duplicate id fails rules-wellformed', async () => {
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('id: git-001', 'id: style-001') })), 'rules-wellformed', /not git-NNN/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('id: naming-004', 'id: naming-003') })), ['rules-wellformed'], /duplicate rule id naming-003/);
  });

  test('too few rules fails rules-wellformed', async () => {
    const few = INDEX.split('  imports:')[0];
    kit.expectFails(await kit.runEval(ID, agent({ index: few })), 'rules-wellformed', /only 6 rules, expected|rules in only 2 categories/);
  });

  test('replacing the index instead of merging fails merge-preserved (seeded testing rule dropped)', async () => {
    const replaced = INDEX.replace(/ {4}- id: testing-001\n.*\n/, '').replace('id: testing-002', 'id: testing-001');
    kit.expectFails(await kit.runEval(ID, agent({ index: replaced })), 'merge-preserved', /testing-001 no longer says|seeded rule/, { only: true });
  });

  test('restarting numbering (a new rule numbered below the seeded one) fails merge-preserved', async () => {
    const clash = INDEX.replace(/id: testing-002/, 'id: testing-000').replace('id: naming-002', 'id: naming-000');
    kit.expectFails(await kit.runEval(ID, agent({ index: clash })), 'merge-preserved', /does not continue after/, { only: true });
  });

  test('generic rules that do not describe this codebase fail rules-grounded', async () => {
    const generic = INDEX.replace('Functions and variables use camelCase', 'Use descriptive names').replace('Throw ValidationError (extends Error) with the offending field', 'Handle errors explicitly')
      .replace('Test files live in test/ and are named *-test.js', 'Write tests for new code').replace('Modules are re-exported through the src/index.js barrel', 'Keep imports tidy')
      .replace('Error classes end in Error', 'Name errors clearly').replace('example: ValidationError', 'example: MyError');
    kit.expectFails(await kit.runEval(ID, agent({ index: generic })), 'rules-grounded', /only \d of 4 facts/, { only: true });
  });

  test('a rule about another stack fails rules-grounded', async () => {
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('Run npm test before committing', 'Run pytest before committing') })), 'rules-grounded', /pytest/, { only: true });
  });

  test('a category with more than 3 rules and no expanded file fails category-docs', async () => {
    kit.expectFails(await kit.runEval(ID, agent({ naming: null })), 'category-docs', /standards\/naming\.md was not written/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ naming: '# Naming\n' })), 'category-docs', /empty or a stub/, { only: true });
  });

  test('CLAUDE.md untouched, overwritten or double-appended fails claude-pointer', async () => {
    kit.expectFails(await kit.runEval(ID, agent({ claude: null })), 'claude-pointer', /no pointer/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ claude: '## Standards\nSee `standards/index.yml`.\n' })), 'claude-pointer', /lost its original content/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ claude: `${CLAUDE}\n## Standards\nSee \`standards/index.yml\`.\n` })), 'claude-pointer', /2 times/, { only: true });
  });

  test('source edited or a stray file written fails scope-only', async () => {
    kit.expectFails(await kit.runEval(ID, agent({ extra: { 'src/errors.js': '// edited\n' } })), 'scope-only', /src\/errors\.js was modified/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ extra: { 'docs/standards.md': '# notes\n' } })), 'scope-only', /docs\/standards\.md/, { only: true });
    kit.expectFails(await kit.runEval(ID, (ws) => { agent()(ws); ws.remove('test/order-test.js'); }), 'scope-only', /was deleted/, { only: true });
  });

  test('an index missing a top-level key or with an empty version/generated fails index-saved', async () => {
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('generated: 2026-11-13\n', '') })), ['index-saved', 'index-stack', 'rules-wellformed', 'merge-preserved', 'rules-grounded', 'category-docs'], /no top-level "generated"/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('generated: 2026-11-13', 'generated:') })), 'index-saved', /empty/, { only: true });
  });

  test('a wrong language or linter fails index-stack', async () => {
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('language: JavaScript (Node.js)', 'language: Python') })), 'index-stack', /the fixture is JavaScript/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('linter: eslint', 'linter: pylint') })), 'index-stack', /the fixture uses eslint/, { only: true });
  });

  test('an unknown category, an empty rule or a long example fails rules-wellformed', async () => {
    const extra = `${INDEX}  security:\n    - id: security-001\n      rule: Validate input\n`;
    kit.expectFails(await kit.runEval(ID, agent({ index: extra })), 'rules-wellformed', /unknown category "security"/, { only: true });
    kit.expectFails(await kit.runEval(ID, agent({ index: INDEX.replace('rule: Classes use PascalCase', 'rule: ""') })), 'rules-wellformed', /naming-003 has an empty rule/, { only: true });
    const longExample = INDEX.replace('example: LineItem', `example: ${'x'.repeat(60)}`);
    kit.expectFails(await kit.runEval(ID, agent({ index: longExample })), 'rules-wellformed', /naming-003 example is 60 characters/, { only: true });
  });

  test('a seeded rule whose id disappeared fails merge-preserved', async () => {
    const dropped = INDEX.replace(/ {4}- id: naming-001\n.*\n.*\n/, '');
    kit.expectFails(await kit.runEval(ID, agent({ index: dropped })), 'merge-preserved', /seeded rule naming-001 is gone/, { only: true });
  });

  test('a deleted CLAUDE.md fails claude-pointer', async () => {
    kit.expectFails(await kit.runEval(ID, (ws) => { agent({ claude: null })(ws); ws.remove('CLAUDE.md'); }), 'claude-pointer', /CLAUDE\.md is missing/, { only: true });
  });

  test('arms: baseline loads nothing, with-skill loads packages/core; the command prefixes only the with-skill prompt', async () => {
    const { baseline, withSkill } = await kit.armsFor(ID);
    expect(baseline.plugins).toEqual([]);
    expect(withSkill.plugins).toHaveLength(1);
    expect(withSkill.prompt.startsWith('/ensemble-core:ensemble:discover-standards ')).toBe(true);
    expect(baseline.prompt).not.toMatch(/^\//);
  }, 60000);
});
