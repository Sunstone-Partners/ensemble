'use strict';

/**
 * Proof that the `ensemble-configure-team` checks pass on a good run and fail on plausible wrong ones. The "agent" is a stub that edits the
 * seeded TRD the way a good or a bad run would; no model is called.
 */

const fs = require('fs');
const kit = require('../skill-eval-kit');
const { CHECKS } = require('../../checks/ensemble-configure-team');

const ID = 'ensemble-configure-team';
const TRD = 'docs/TRD/TRD-2026-c0ffee01-notes-api.md';
const IDS = ['section-injected', 'metrics-counts', 'tier-complex', 'domains', 'depth', 'lead-role', 'builders', 'complex-roles', 'trd-preserved', 'no-stray-files'];
const SECTION_IDS = IDS.filter((i) => i !== 'no-stray-files');

const HEADER = `## 4.1 Team Configuration

> **Auto-generated by \`/ensemble:configure-team\`** - edit agent assignments below if needed.

### Complexity Metrics

| Metric | Value |
|--------|-------|
| Task count | 12 |
| Estimated hours | ~72h |
| Domain count | 5 (backend, frontend, database, infrastructure, testing) |
| Cross-cutting tasks | 2 |
| Dependency depth | 5 (TRD-001, TRD-002, TRD-003, TRD-004, TRD-005) |
| **Team tier** | **Complex** |
`;

const YAML = `team:
  roles:
    - name: lead
      agent: tech-lead-orchestrator
      owns:
        - task-selection
        - architecture-review
        - final-approval
    - name: builder
      agents:
        - backend-developer
        - frontend-developer
        - postgresql-specialist
      owns:
        - implementation
    - name: reviewer
      agent: code-reviewer
      owns:
        - code-review
    - name: qa
      agent: test-runner
      owns:
        - test-execution
`;

const section = (header = HEADER, yaml = YAML) => `${header}\n\`\`\`yaml\n${yaml}\`\`\`\n\n`;

/** Insert `sec` before the Quality Requirements heading of the seeded TRD (what INSERT mode does). */
const inserted = (orig, sec) => orig.replace('## 5. Quality Requirements', `${sec}## 5. Quality Requirements`);

/** A stub agent: edit the seeded TRD with `edit(originalText)`; extra files may be written. */
const edits = (edit, extra = {}) => (ws) => {
  ws.write(TRD, edit(ws.read(TRD)));
  for (const [rel, body] of Object.entries(extra)) ws.write(rel, body);
};
const good = (sec = section()) => edits((o) => inserted(o, sec));

describe(`${ID} checks`, () => {
  test('loads clean: valid definition, fixture without agent or git configuration', () => {
    kit.loadsClean(ID);
  });

  test('a good run passes every check', async () => {
    const res = await kit.runEval(ID, good());
    expect(Object.keys(res)).toEqual(IDS);
    kit.expectAllPass(res);
  });

  test('the check table and eval.json list the same checks', () => {
    expect(Object.keys(CHECKS)).toEqual(IDS);
  });

  test('the lead:/builders: block shape of a shipped TRD is accepted by the role parser', async () => {
    const shipped = `team:
  lead:
    agent: tech-lead-orchestrator
    owns:
      - task-selection
      - architecture-review
      - final-approval
  builders:
    - agent: frontend-developer
      owns:
        - implementation
    - agent: backend-developer
      owns:
        - implementation
  reviewer:
    agent: code-reviewer
  qa:
    agent: test-runner
`;
    kit.expectAllPass(await kit.runEval(ID, good(section(HEADER, shipped))));
  });

  test('a run that changes nothing fails every section check; the seeded TRD alone passes none of them', async () => {
    const res = await kit.runEval(ID, () => {});
    kit.expectFails(res, SECTION_IDS, /Team Configuration/, { only: true });
  });

  test('miscounting the nested-description tasks (8 instead of 12, 46h instead of 72h) fails metrics-counts', async () => {
    const res = await kit.runEval(ID, good(section(HEADER.replace('| Task count | 12 |', '| Task count | 8 |').replace('~72h', '~46h'))));
    kit.expectFails(res, 'metrics-counts', /task count is 8/, { only: true });
  });

  test('the Medium tier for a 72-hour TRD fails tier-complex', async () => {
    const res = await kit.runEval(ID, good(section(HEADER.replace('**Complex**', '**Medium**'))));
    kit.expectFails(res, 'tier-complex', /tier is Medium/, { only: true });
  });

  test('a single-domain analysis fails domains', async () => {
    const res = await kit.runEval(ID, good(section(HEADER.replace(/\| Domain count \|[^\n]*/, '| Domain count | 1 (backend) |'))));
    kit.expectFails(res, 'domains', /domain count is 1/, { only: true });
  });

  test('a nonsense dependency depth fails depth', async () => {
    const res = await kit.runEval(ID, good(section(HEADER.replace(/\| Dependency depth \|[^\n]*/, '| Dependency depth | 12 |'))));
    kit.expectFails(res, 'depth', /dependency depth is 12/, { only: true });
  });

  test('a lead that is not tech-lead-orchestrator, or that owns too little, fails lead-role', async () => {
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, YAML.replace('agent: tech-lead-orchestrator', 'agent: architect')))), 'lead-role', /not tech-lead-orchestrator/, { only: true });
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, YAML.replace('        - final-approval\n', '')))), 'lead-role', /does not own final-approval/, { only: true });
  });

  test('an invented builder agent, or a single builder, fails builders', async () => {
    const invented = YAML.replace('postgresql-specialist', 'fullstack-wizard');
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, invented))), 'builders', /fullstack-wizard/, { only: true });
    const single = YAML.replace('        - frontend-developer\n', '').replace('        - postgresql-specialist\n', '');
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, single))), 'builders', /only 1 builder agent/, { only: true });
  });

  test('a builder role that does not own implementation fails builders', async () => {
    const res = await kit.runEval(ID, good(section(HEADER, YAML.replace('      owns:\n        - implementation\n', '      owns:\n        - coding\n'))));
    kit.expectFails(res, 'builders', /does not own implementation/, { only: true });
  });

  test('a Complex team without reviewer and qa roles (the Medium shape) fails complex-roles', async () => {
    const medium = YAML.slice(0, YAML.indexOf('    - name: reviewer'));
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, medium))), 'complex-roles', /no reviewer role/, { only: true });
  });

  test('a reviewer or qa role filled by the wrong agent fails complex-roles', async () => {
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, YAML.replace('agent: test-runner', 'agent: backend-developer')))), 'complex-roles', /qa role is not test-runner/, { only: true });
  });

  test('right task count but wrong hours (a 46h sum that skips the nested-description tasks) fails metrics-counts', async () => {
    const res = await kit.runEval(ID, good(section(HEADER.replace('~72h', '~46h'))));
    kit.expectFails(res, 'metrics-counts', /estimated hours is 46/, { only: true });
  });

  test('domains listed without the frontend fail domains', async () => {
    const res = await kit.runEval(ID, good(section(HEADER.replace('backend, frontend, database, infrastructure, testing', 'backend, database, infrastructure, testing'))));
    kit.expectFails(res, 'domains', /frontend domain/, { only: true });
  });

  test('a reviewer role filled by the wrong agent, or a missing qa role, fails complex-roles with its own reason', async () => {
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, YAML.replace('agent: code-reviewer', 'agent: backend-developer')))), 'complex-roles', /reviewer is not code-reviewer/, { only: true });
    const noQa = YAML.slice(0, YAML.indexOf('    - name: qa'));
    kit.expectFails(await kit.runEval(ID, good(section(HEADER, noQa))), 'complex-roles', /no qa role/, { only: true });
  });

  test('a section with no yaml block fails the three role checks', async () => {
    const res = await kit.runEval(ID, good(`${HEADER}\nLead: tech-lead-orchestrator.\n\n`));
    kit.expectFails(res, ['lead-role', 'builders', 'complex-roles'], /fenced yaml block/, { only: true });
  });

  test('injecting at the end of the file, after Quality Requirements and the Appendix, fails section-injected', async () => {
    const res = await kit.runEval(ID, edits((o) => `${o}\n${section()}`));
    kit.expectFails(res, 'section-injected', /not between the Master Task List and Quality Requirements/, { only: true });
  });

  test('two Team Configuration sections fail every section check', async () => {
    const res = await kit.runEval(ID, good(section() + section()));
    kit.expectFails(res, SECTION_IDS, /2 Team Configuration headings/, { only: true });
  });

  test('editing a task estimate while injecting fails trd-preserved', async () => {
    const res = await kit.runEval(ID, edits((o) => inserted(o, section()).replace('(6h) [satisfies: REQ-001]\n- [ ] **TRD-002', '(8h) [satisfies: REQ-001]\n- [ ] **TRD-002')));
    kit.expectFails(res, 'trd-preserved', /changed outside the section/, { only: true });
  });

  test('deleting the Quality Requirements section while injecting fails trd-preserved and section-injected', async () => {
    const res = await kit.runEval(ID, edits((o) => inserted(o, section()).replace(/## 5\. Quality Requirements[\s\S]*?(?=## 6\.)/, '')));
    kit.expectFails(res, ['trd-preserved', 'section-injected'], undefined, { only: true });
  });

  test('implementation files written next to a good TRD fail no-stray-files', async () => {
    const res = await kit.runEval(ID, edits((o) => inserted(o, section()), { 'src/notes.js': 'module.exports = {};\n' }));
    kit.expectFails(res, 'no-stray-files', /src\/notes\.js/, { only: true });
  });

  test('a symlinked TRD is not followed', async () => {
    const res = await kit.runEval(ID, (ws) => {
      const full = `${ws.dir}/${TRD}`;
      fs.writeFileSync(`${ws.root}/elsewhere.md`, inserted(ws.read(TRD), section()));
      fs.unlinkSync(full);
      fs.symlinkSync(`${ws.root}/elsewhere.md`, full);
    });
    kit.expectFails(res, SECTION_IDS, /symlink/);
  });

  test('arms: baseline loads nothing, with-skill loads packages/development; the command prefixes only the with-skill prompt', async () => {
    const { baseline, withSkill } = await kit.armsFor(ID);
    expect(baseline.plugins).toEqual([]);
    expect(withSkill.plugins).toHaveLength(1);
    expect(withSkill.prompt.startsWith('/ensemble-development:ensemble:configure-team ')).toBe(true);
    expect(baseline.prompt).not.toMatch(/^\//);
  }, 60000);
});
